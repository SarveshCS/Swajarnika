@register.simple_tag
def icon(name, size=18, **kwargs):
    """Render an inline Lucide SVG.

    kwargs['class'] is appended to the default `lucide` class.
    """
    body = _ICONS.get(name)
    if body is None:
        return mark_safe(f"<!-- icon:{name} not found -->")
    extra_cls = kwargs.get("class", "")
    klass = f"lucide {extra_cls}".strip()
    sw = kwargs.get("stroke_width", "1.5")
    aria = 'aria-hidden="true"'
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" class="{klass}" '
        f'width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="none" stroke="currentColor" stroke-width="{sw}" '
        f'stroke-linecap="round" stroke-linejoin="round" {aria}>'
        f'{body}</svg>'
    )
    return mark_safe(svg)
